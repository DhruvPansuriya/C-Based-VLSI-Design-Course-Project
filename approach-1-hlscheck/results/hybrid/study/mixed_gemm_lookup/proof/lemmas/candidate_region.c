void gemm_lookup(unsigned int m1[16], unsigned int m2[16], unsigned int prod[16], unsigned int index)
{
  for (int p = 0; p < 16; p++)
  {
    prod[p] = 0u;
  }

  for (int i = 0; i < 4; i++)
  {
    for (int k = 0; k < 4; k++)
    {
      unsigned int a = m1[(i * 4) + k];
      for (int j = 0; j < 4; j++)
      {
        prod[(i * 4) + j] += a * m2[(k * 4) + j];
      }

    }

  }

}


